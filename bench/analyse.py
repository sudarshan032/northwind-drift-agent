"""Summarise benchmark results into tables (BENCH_SPEC 4-5; charts and RESULTS.md come in session 2).

    python -m bench.analyse [--out bench/results/SUMMARY.md]

Query shapes, in plain words: FalkorDB answers a blast radius with one breadth-first search call over the
impact edges, inside the database, following adjacency directly. PostgreSQL answers it with a recursive
query: each round joins the current frontier with the edge table through an index, so a depth-10 radius is
up to ten rounds of index lookups plus de-duplication.
"""

import argparse
import glob
import json
import os

from bench import config as C


def rows(size, name):
    p = os.path.join(C.RESULTS, str(size), f"{name}.jsonl")
    return [json.loads(x) for x in open(p)] if os.path.exists(p) else []


def mb(b):
    return f"{float(b or 0) / 2**20:,.0f} MB"


def summary():
    sizes = sorted(int(os.path.basename(d)) for d in glob.glob(os.path.join(C.RESULTS, "*")) if os.path.basename(d).isdigit())
    out = ["# Benchmark summary (generated by bench/analyse.py)", ""]
    for size in sizes:
        gen = rows(size, "generate")
        if not gen:
            continue
        g = gen[0]
        out += [f"## {g['nodes']:,} nodes, {g['edges']:,} edges ({g['regions']} regions, {g['hospitals']} hospitals)",
                "", f"Generated in {g['seconds']} s, generator peak RSS {mb(g['peak_rss_bytes'])}, "
                    f"CSV {mb(g['bytes_on_disk'])}.", ""]
        fl, pl = rows(size, "falkordb_load"), rows(size, "postgres_load")
        if fl and pl:
            out += ["| | FalkorDB | PostgreSQL |", "|---|---|---|",
                    f"| load (s) | {fl[0]['seconds']['load_total']} (impact layer {fl[0]['seconds']['impact_build']}) "
                    f"| {pl[0]['seconds']['load_total']} |",
                    f"| peak memory during load | {mb(fl[0]['peak_memory_bytes'])} | {mb(pl[0]['peak_memory_bytes'])} |",
                    f"| impact edges | {sum(fl[0]['impact_edges'].values()):,} | same rows (COPY) |"]
            res = rows(size, "resources")
            if res:
                f, p = res[0], res[1]
                out += [f"| on disk | {mb(f['disk_bytes'])} (RDB) | {mb(p['disk_bytes'])} (tables + indexes) |",
                        f"| graph / container memory | {f['graph_memory_mb']} MB / {mb(f['container_memory_bytes'])} "
                        f"| {mb(p['container_memory_bytes'])} |"]
            out.append("")
        dep = [r for r in rows(size, "depth") if "start" in r]
        if dep:
            out += ["| query | start | depth | reached | FalkorDB median / p95 (ms) | PostgreSQL median / p95 (ms) | faster |",
                    "|---|---|---|---|---|---|---|"]
            for kind, start in dict.fromkeys((r.get("kind", "radius"), r["start"]) for r in dep):
                for d in C.DEPTHS:
                    pick = lambda sysname: next((r for r in dep if r.get("kind", "radius") == kind and r["start"] == start
                                                 and r["depth"] == d and r["system"] == sysname), None)
                    f, p = pick("falkordb"), pick("postgres")
                    if f and p:
                        ratio = p["median_ms"] / f["median_ms"] if f["median_ms"] else 0
                        who = f"FalkorDB {ratio:.1f}x" if ratio >= 1 else f"PostgreSQL {1 / ratio:.1f}x"
                        out.append(f"| {kind} | `{start}` | {d} | {f['reached']:,} | {f['median_ms']} / {f['p95_ms']} | "
                                   f"{p['median_ms']} / {p['p95_ms']} | {who} |")
            gate = [r for r in rows(size, "depth") if r.get("gate")]
            out += ["", f"Correctness gate: {gate[0]['gate'] if gate else 'not run'} "
                        f"({gate[0]['pairs_checked'] if gate else 0} start/depth pairs, identical node sets).", ""]
        cr = rows(size, "change_review")
        if cr:
            out += ["Change review CHG-HEADLINE (declared + real radius + difference): " + ", ".join(
                f"{r['system']} median {r['median_ms']} ms, p95 {r['p95_ms']} ms" for r in cr) +
                f"; declared {cr[0]['declared']} vs real {cr[0]['real']} components, {cr[0]['hidden']} hidden, "
                f"{cr[0]['hospitals_real']} hospitals.", ""]
        conc = rows(size, "concurrency_falkordb") + rows(size, "concurrency_postgres")
        if conc:
            out += ["| clients | system | queries/s | p50 (ms) | p95 (ms) | p99 (ms) | errors |",
                    "|---|---|---|---|---|---|---|"]
            for n in C.CLIENTS:
                for r in conc:
                    if r["clients"] == n:
                        out.append(f"| {n} | {r['system']} | {r['throughput_qps']} | {r.get('p50_ms')} | "
                                   f"{r.get('p95_ms')} | {r.get('p99_ms')} | {r['errors']} |")
            out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(C.RESULTS, "SUMMARY.md"))
    a = ap.parse_args()
    text = summary()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write(text + "\n")
    print(text)
